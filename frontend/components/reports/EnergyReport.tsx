    title: { fontSize: 28, fontWeight: 'bold', marginBottom: 10, color: '#333' },
    subtitle: { fontSize: 14, color: '#666', marginBottom: 20 },
    sectionTitle: { fontSize: 18, color: '#1A73E8', marginTop: 20, marginBottom: 10, borderBottomWidth: 1, borderBottomStyle: 'solid', borderBottomColor: '#eee', paddingBottom: 5 },

    // Grid/Cards
    grid2x2: { flexDirection: 'row', flexWrap: 'wrap', justifyContent: 'space-between', marginTop: 10 },
    card: { width: '48%', backgroundColor: '#f8f9fa', padding: 15, borderRadius: 8, marginBottom: 15, borderWidth: 1, borderStyle: 'solid', borderColor: '#eee' },
    cardTitle: { fontSize: 12, color: '#666', marginBottom: 5 },
    cardValue: { fontSize: 20, fontWeight: 'bold', color: '#1A73E8' },

    // Tables
    table: { width: '100%', marginTop: 10 },
    tableRow: { flexDirection: 'row', borderBottom: '1px solid #eee', paddingVertical: 8, alignItems: 'center' },
    tableHeader: { backgroundColor: '#f8f9fa', fontWeight: 'bold' },
    tableCell: { flex: 1, fontSize: 10, color: '#333' },
    tableCellNum: { flex: 1, fontSize: 10, color: '#333', textAlign: 'right' },

    text: { fontSize: 11, color: '#333', lineHeight: 1.5, marginBottom: 5 },
    bulletList: { marginLeft: 10, marginTop: 5 },
    bulletItem: { fontSize: 11, color: '#333', marginBottom: 5 },

    // Specific blocks
    coverBox: { backgroundColor: '#1A73E8', padding: 40, borderRadius: 10, marginTop: 50 },
