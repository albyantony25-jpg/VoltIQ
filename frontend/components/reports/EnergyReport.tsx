    highlightBox: { backgroundColor: '#e8f0fe', padding: 15, borderRadius: 5, marginTop: 10, borderLeft: '4px solid #1A73E8' },
    heatmapRow: { flexDirection: 'row', flexWrap: 'wrap', gap: 2, marginTop: 10 },
    heatmapCell: { width: 45, height: 45, justifyContent: 'center', alignItems: 'center', backgroundColor: '#e8f0fe', margin: 2, borderRadius: 4 },
    heatmapText: { fontSize: 8, color: '#1A73E8' },
